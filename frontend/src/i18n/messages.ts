function getLeaf(obj: MessageTree | string | undefined, path: string[]): string | undefined {
  if (!obj || typeof obj === 'string') return typeof obj === 'string' ? obj : undefined
  if (path.length === 0) return undefined
  const [head, ...rest] = path
  const next = obj[head]
  if (rest.length === 0) return typeof next === 'string' ? next : undefined
  if (next && typeof next === 'object') return getLeaf(next as MessageTree, rest)
  return undefined
}

export function resolveMessage(locale: Locale, key: string): string | undefined {
  const path = key.split('.').filter(Boolean)
  const primary = getLeaf(messages[locale] as MessageTree, path)
  if (primary) return primary
  if (locale !== 'en') return getLeaf(messages.en as MessageTree, path)
  return undefined
}
